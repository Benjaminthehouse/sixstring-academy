/**
 * Hearts: the mistake budget of theory lessons. Pure functions over `HeartsState`.
 *
 * Regeneration is lazy: nothing ticks. The state stores the count and when the current
 * regeneration period started, and the true count at any moment is derived from the clock.
 */
import { HEART_REGEN_MINUTES, MAX_HEARTS } from './catalog';
import type { HeartsState } from './types';

/** Milliseconds one heart takes to come back. */
export const HEART_REGEN_MS = HEART_REGEN_MINUTES * 60_000;

/** A full set of hearts. */
export const FULL_HEARTS: HeartsState = { count: MAX_HEARTS, regenFrom: null };

/** Apply every heart that has regenerated by `now`. Returns the same object when nothing changed. */
export function settleHearts(hearts: HeartsState, now: number): HeartsState {
  if (hearts.count >= MAX_HEARTS) {
    return hearts.count === MAX_HEARTS && hearts.regenFrom === null ? hearts : { count: MAX_HEARTS, regenFrom: null };
  }
  // A device clock that jumped backwards must not stall regeneration: restart the period at `now`.
  if (hearts.regenFrom === null || hearts.regenFrom > now) return { count: Math.max(0, hearts.count), regenFrom: now };
  const gained = Math.floor((now - hearts.regenFrom) / HEART_REGEN_MS);
  if (gained <= 0) return hearts;
  const count = Math.min(MAX_HEARTS, hearts.count + gained);
  return { count, regenFrom: count >= MAX_HEARTS ? null : hearts.regenFrom + gained * HEART_REGEN_MS };
}

/** Take one heart away (never below zero). */
export function removeHeart(hearts: HeartsState, now: number): HeartsState {
  const settled = settleHearts(hearts, now);
  if (settled.count <= 0) return settled;
  return { count: settled.count - 1, regenFrom: settled.regenFrom ?? now };
}

/** Give hearts back. */
export function addHearts(hearts: HeartsState, amount: number, now: number): HeartsState {
  const settled = settleHearts(hearts, now);
  const count = Math.min(MAX_HEARTS, settled.count + Math.max(0, Math.floor(amount)));
  if (count === settled.count) return settled;
  return { count, regenFrom: count >= MAX_HEARTS ? null : settled.regenFrom };
}

/** What a hearts display needs. */
export interface HeartsView {
  count: number;
  max: number;
  full: boolean;
  /** No hearts left: a theory lesson cannot be started (never true in unlimited mode). */
  empty: boolean;
  /** Relaxed mode: hearts are not used. */
  unlimited: boolean;
  /** When the next heart arrives (epoch ms), or null when full. */
  nextAt: number | null;
  msToNext: number;
  msToFull: number;
}

/** The hearts as they are at `now`. */
export function heartsView(hearts: HeartsState, now: number, unlimited = false): HeartsView {
  if (unlimited) {
    return { count: MAX_HEARTS, max: MAX_HEARTS, full: true, empty: false, unlimited: true, nextAt: null, msToNext: 0, msToFull: 0 };
  }
  const settled = settleHearts(hearts, now);
  const full = settled.count >= MAX_HEARTS;
  const nextAt = full || settled.regenFrom === null ? null : settled.regenFrom + HEART_REGEN_MS;
  const msToNext = nextAt === null ? 0 : Math.max(0, nextAt - now);
  const msToFull = nextAt === null ? 0 : msToNext + (MAX_HEARTS - settled.count - 1) * HEART_REGEN_MS;
  return { count: settled.count, max: MAX_HEARTS, full, empty: settled.count <= 0, unlimited: false, nextAt, msToNext, msToFull };
}
