/**
 * Hand-authored part of a scale. A formula, a `parent` + `mode`, or both: with both, the formula
 * fixes the degree spelling and the tests still check that its notes are that mode of the parent.
 */
export interface RawScale {
  id: string;
  name: string;
  aliases: string[];
  /** Degree formula against the major scale, e.g. `1 2 b3 4 5 b6 b7`. */
  formula?: string;
  /** Id of the scale this is a mode of. A family's own parent names itself with mode 1. */
  parent?: string;
  /** 1-based mode number within the parent. */
  mode?: number;
  family: ScaleFamily;
  /** 1 beginner … 4 expert. */
  tier: 1 | 2 | 3 | 4;
  /** What it sounds and feels like. */
  description: string;
  /** Where and how it is used. */
  uses: string;
  genres: string[];
  /** Chord-type ids it is usually played over. */
  chords: string[];
  /** Mood and usage tags; size and quality tags are derived. */
  tags: string[];
}

interface Extra {
  aliases?: string[];
  formula?: string;
  parent?: string;
  mode?: number;
  genres?: string[];
  chords?: string[];
  tags?: string[];
}

function def(
  id: string, name: string, family: ScaleFamily, tier: 1 | 2 | 3 | 4, description: string, uses: string, extra: Extra,
): RawScale {
  return {
    id, name, family, tier, description, uses,
    aliases: extra.aliases ?? [],
    formula: extra.formula,
    parent: extra.parent,
    mode: extra.mode,
    genres: extra.genres ?? [],
    chords: extra.chords ?? [],
    tags: extra.tags ?? [],
  };
}

