/**
 * The scale catalog. Only what cannot be computed is typed here: names, aliases, prose, the
 * chords a scale is usually played over, and one degree formula per scale *family*. A mode is
 * declared as "mode n of parent" and its formula is derived by rotation in `scale.ts`, so a mode
 * can never disagree with its parent. The tests cross-check every derived formula against an
 * independently typed table.
 */

/** Grouping used by the scale explorer. */
export type ScaleFamily =
  | 'diatonic' | 'melodic-minor' | 'harmonic-minor' | 'harmonic-major' | 'double-harmonic'
  | 'pentatonic' | 'blues' | 'bebop' | 'symmetric' | 'exotic';

/** Display information for a scale family. */
