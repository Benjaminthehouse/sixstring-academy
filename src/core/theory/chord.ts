/** Canonical text for "no chord". */
export const NO_CHORD = 'N.C.';
const NO_CHORD_RE = /^(n\.?\s*c\.?|n\/c|no\s*chord|tacet)$/i;

/** True for the "no chord" marks found on charts: `N.C.`, `NC`, `no chord`, `tacet`. */
export function isNoChord(symbol: string): boolean {
  return NO_CHORD_RE.test(symbol.trim());
}

function normalizeSuffix(raw: string): string {
  let s = raw
    .replace(/♯/g, '#').replace(/♭/g, 'b')
    .replace(/[△∆Δ]/g, '^').replace(/[°º˚⁰ᵒ]/g, '°').replace(/[øØ∅⌀]/g, 'ø')
    .replace(/[−–—]/g, '-').replace(/＋/g, '+')
    // Postfix signs inside brackets, as Brazilian and older European charts write them:
    // C7(9-) = C7b9, Cm7(5-) = Cm7b5, C7(5+) = C7#5, E7(9-/13-) = E7b9b13.
    .replace(/(?<=[(\[{,/\s])(13|11|9|5)([+-])(?=[)\]},/\s]|$)/g, '$2$1')
    .replace(/6\s*\/\s*9/g, '69')
    .replace(/[\s()[\]{},/.]/g, '');
  // "7M" is how those same charts write a major seventh: C7M = Cmaj7, Cm7M = CmMaj7.
  s = s.replace(/(7|9|11|13)M(?![a-zA-Z0-9])/g, 'maj$1');
  // A capital M means major, a small m minor; settle that before lower-casing everything.
  // "Mm" claims both at once and is no chord.
  if (/^Mm/.test(s)) return '?';
  if (/^M(add|ADD)/.test(s)) s = s.slice(1);
  else if (/^M(?![aAiI])/.test(s)) s = /^M(7|9|11|13)/.test(s) ? `maj${s.slice(1)}` : s.slice(1);
  if (s.length > 1) s = s[0] + s.slice(1).replace(/M(?=7|9|11|13)/g, 'maj');
  return s.toLowerCase();
}

const ALTERATIONS: Record<string, string> = {
  // "#4" is the raised eleventh under its everyday name (Fmaj7#4).
  b5: 'd5', '#5': 'A5', b6: 'm6', b9: 'm9', '#9': 'A9', '#4': 'A11', '#11': 'A11', b13: 'm13',
};

/** Read a chord-symbol suffix into its interval set; null when it makes no sense. */
function parseSuffix(raw: string): string[] | null {
  const s = normalizeSuffix(raw);
  let minor = false, majFlag = false, delta = false, dim = false, halfDim = false, aug = false, dom = false, alt = false;
  let power = false, sus2 = false, sus4 = false, six = false, sharpSeven = false;
  let ext = 0;
  const altered: string[] = [];
  const adds: Array<{ acc: string; n: number }> = [];
  const omit: number[] = [];
  let previous = '';

  let i = 0;
  while (i < s.length) {
    const rest = s.slice(i);
    let m: RegExpExecArray | null;
    let token = '';
    if ((m = /^(major|maj|ma(?=\d|$)|\^|j(?=7))/.exec(rest))) {
      if (majFlag) return null;
      majFlag = true;
      if (m[0] === '^') delta = true;
      token = 'maj';
    } else if ((m = /^(minor|min|mi(?=\d|$|add|sus|ma|\^|no|omit|[b#+-])|m)/.exec(rest))) {
      if (minor) return null;
      minor = true;
      token = 'min';
    } else if (i === 0 && (m = /^-(?!5)/.exec(rest))) {
      minor = true;
      token = 'min';
    } else if ((m = /^(diminished|dim|°)/.exec(rest)) || (i === 0 && (m = /^o(?=\d|$|maj)/.exec(rest)))) {
      dim = true;
      token = 'dim';
    } else if ((m = /^(ø|hdim|half-?dim(?:inished)?)/.exec(rest))) {
      halfDim = true;
      token = 'hdim';
    } else if ((m = /^(augmented|aug)/.exec(rest))) {
      aug = true;
      token = 'aug';
    } else if ((m = /^(dominant|dom)/.exec(rest))) {
      dom = true;
      token = 'dom';
    } else if ((m = /^alt/.exec(rest))) {
      alt = true;
      token = 'alt';
    } else if ((m = /^sus(2sus4|4sus2|24|42)/.exec(rest))) {
      sus2 = sus4 = true;
      token = 'sus';
    } else if ((m = /^sus(2|4)?/.exec(rest))) {
      if (m[1] === '2') sus2 = true;
      else sus4 = true;
      token = 'sus';
    } else if ((m = /^add(b|#|\+|-)?(13|11|9|6|4|2)/.exec(rest))) {
      const acc = m[1] === '+' ? '#' : m[1] === '-' ? 'b' : m[1] ?? '';
      adds.push({ acc, n: parseInt(m[2], 10) });
      token = 'add';
    } else if ((m = /^(?:no|omit)(3|5)(?:rd|th)?/.exec(rest))) {
      omit.push(parseInt(m[1], 10));
      token = 'omit';
    } else if ((m = /^#7/.exec(rest)) || (previous === 'min' && (m = /^\+7/.exec(rest)))) {
      // Cm#7 and Cm+7 both raise the seventh of a minor chord: the minor major seventh.
      sharpSeven = true;
      token = 'alter';
    } else if (i === 0 && (m = /^5([+-])(?!\d)/.exec(rest))) {
      // C5+ and C5- are old spellings of the augmented triad and the flat-five triad.
      altered.push(m[1] === '+' ? 'A5' : 'd5');
      token = 'alter';
    } else if ((m = /^(b|#|-)(13|11|9|6|5|4)/.exec(rest)) || (m = (i > 0 ? /^(\+)(13|11|9|5)/ : /^(\+)(5)/).exec(rest))) {
      // A leading plus is the augmented triad (C+9 = C9#5); after a number it raises a tone (C7+9).
      const sign = m[1];
      const name = `${sign === 'b' || sign === '-' ? 'b' : '#'}${m[2]}`;
      const target = ALTERATIONS[name];
      if (!target) return null;
      altered.push(target);
      token = 'alter';
    } else if ((m = /^\+/.exec(rest))) {
      aug = true;
      token = 'aug';
    } else if ((m = /^(69|13|11|9|7|6|5|4|2)/.exec(rest))) {
      const n = parseInt(m[1], 10);
      token = 'number';
      if (n === 69) {
        six = true;
        adds.push({ acc: '', n: 9 });
      } else if (n === 6) {
        six = true;
      } else if (n >= 7) {
        // The first number is the chord's extension; a later one (C7(13), Cm7(11)) is an added tone.
        if (ext === 0) ext = n;
        else if (n !== 7) adds.push({ acc: '', n });
        // A second seventh only makes sense as the "maj7" of C9(maj7); C77 is a typo, not a chord.
        else if (previous !== 'maj') return null;
      } else if (n === 5) {
        if (i === 0) power = true;
        else if (previous !== 'aug') return null;
      } else if (i === 0) {
        if (n === 4) sus4 = true;
        else sus2 = true;
      } else if (n === 4 && ext > 0) {
        // G7/4 and G7(4): the fourth replaces the third. On a minor chord it is the added eleventh.
        if (minor) adds.push({ acc: '', n: 11 });
        else sus4 = true;
      } else {
        return null;
      }
    } else {
      return null;
    }
    previous = token;
    i += m[0].length;
  }

  if (ext === 0 && (delta || dom || halfDim || alt || (minor && majFlag))) ext = 7;
  const suspended = sus2 || sus4;
  // "Csusb9" is the Phrygian chord of jazz charts, a dominant: the seventh is understood.
  if (ext === 0 && suspended && altered.includes('m9')) ext = 7;
  let third: string | null = power || suspended ? null : minor || dim || halfDim ? 'm3' : 'M3';
  let fifth: string | null = dim || halfDim ? 'd5' : aug ? 'A5' : 'P5';
  let seventh: string | null = null;
  if (ext >= 7) seventh = majFlag ? 'M7' : dim ? 'd7' : 'm7';
  if (sharpSeven) seventh = 'M7';

  const tones = new Set<string>();
  if (ext >= 9) tones.add('M9');
  if (ext === 11) tones.add('P11');
  if (ext === 13) tones.add('M13');
  if (six) tones.add('M6');
  if (sus2) tones.add('M2');
  if (sus4) tones.add('P4');

  for (const a of altered) {
    if (a === 'd5' || a === 'A5') fifth = a;
    else {
      if (a === 'm9' || a === 'A9') tones.delete('M9');
      if (a === 'A11') tones.delete('P11');
      if (a === 'm13') tones.delete('M13');
      tones.add(a);
    }
  }
  for (const { acc, n } of adds) {
    let number = n;
    if (n === 2) number = 9;
    // With a seventh an added fourth is the eleventh; "add #4" always means the raised eleventh.
    else if (n === 4 && (seventh || acc !== '')) number = 11;
    // Without a seventh "add 13" is simply the sixth.
    else if (n === 13 && !seventh && acc === '') number = 6;
    try {
      tones.add(degreeToInterval(`${acc}${number}`));
    } catch {
      return null;
    }
  }
  if (alt) {
    // "Alt" is a dominant with its third; a suspended alt chord is a contradiction.
    if (suspended) return null;
    third = 'M3';
    fifth = null;
    seventh = 'm7';
    for (const natural of ['M9', 'P11', 'M13']) tones.delete(natural);
    for (const tension of ['m9', 'A9', 'A11', 'm13']) tones.add(tension);
  }
  if (omit.includes(3)) third = null;
  if (omit.includes(5)) fifth = null;
  // A suspended fourth or second makes the matching tension redundant (C11sus, C9sus2).
  if (tones.has('P4')) tones.delete('P11');
  if (tones.has('M9')) tones.delete('M2');

  const all = ['P1', ...tones];
  if (third) all.push(third);
  if (fifth) all.push(fifth);
  if (seventh) all.push(seventh);
  const sorted = sortIntervals(all);
  // Two names for one pitch (Cm7#9, C7b5#11, Cdim13) means the symbol contradicts itself.
  if (new Set(sorted.map((name) => interval(name).semitones % 12)).size !== sorted.length) return null;
  return sorted.length >= 2 ? sorted : null;
}

/** Generate a canonical suffix for an interval set the catalog does not hold. */
function symbolForIntervals(intervals: string[]): string {
  const has = (name: string) => intervals.includes(name);
  const third = has('M3') ? 'M3' : has('m3') ? 'm3' : null;
  const fifth = has('P5') ? 'P5' : has('d5') ? 'd5' : has('A5') ? 'A5' : null;
  const seventh = has('M7') ? 'M7' : has('m7') ? 'm7' : has('d7') ? 'd7' : null;
  const nine = has('M9');
  const anyNine = nine || has('m9') || has('A9');
  const eleven = has('P11');
  const thirteen = has('M13');
  const minor = third === 'm3' ? 'm' : '';
  const adds: string[] = [];
  let base: string;
  let fifthNamed = false;

  if (seventh === 'd7') {
    base = 'dim7';
    fifthNamed = fifth === 'd5';
    if (nine) adds.push('add9');
    if (eleven) adds.push('add11');
  } else if (seventh) {
    // A natural tension beside its altered twin (9 with b9, 11 with #11, 13 with b13) cannot be
    // the chord's number, because "C9b9" reads as C7b9. It is written as an added note instead.
    const alteredNine = has('m9') || has('A9');
    let n = 7;
    if (thirteen && !has('m13') && anyNine) n = 13;
    else if (eleven && !has('A11') && anyNine) n = 11;
    else if (nine && !alteredNine) n = 9;
    base = `${minor}${seventh === 'M7' ? (minor ? 'Maj' : 'maj') : ''}${n}`;
    if (nine && (n === 7 || alteredNine)) adds.push('add9');
    if (n !== 11 && eleven) adds.push('add11');
    if (n !== 13 && thirteen) adds.push('add13');
    if (has('M6')) adds.push('add6');
  } else {
    let sixNamed = false;
    if (third === 'm3' && fifth === 'd5') {
      base = 'dim';
      fifthNamed = true;
    } else if (third === 'M3' && fifth === 'A5') {
      base = 'aug';
      fifthNamed = true;
    } else {
      base = minor;
      if (has('M6')) {
        base += nine ? '6/9' : '6';
        sixNamed = true;
      }
    }
    if (has('M6') && !sixNamed) adds.push('add6');
    if (nine && !(sixNamed && base.endsWith('6/9'))) adds.push('add9');
    if (eleven) adds.push('add11');
  }
  if (third && has('P4')) adds.push('add4');

  let sus = '';
  let omits = '';
  if (!third) {
    const s2 = has('M2');
    const s4 = has('P4');
    if (s2 && s4) sus = 'sus2sus4';
    else if (s4) sus = 'sus4';
    else if (s2) sus = 'sus2';
    else if (base === '' && fifth === 'P5') base = '5';
    else omits += 'no3';
  }
  if (fifth === null) omits += 'no5';

  // With a seventh, altered tensions are written plainly (7b9); without one they are added notes.
  const tension = seventh ? '' : 'add';
  let alterations = '';
  if (!fifthNamed && fifth === 'd5') alterations += 'b5';
  if (!fifthNamed && fifth === 'A5') alterations += '#5';
  if (has('m9')) alterations += `${tension}b9`;
  if (has('A9')) alterations += `${tension}#9`;
  if (has('A11')) alterations += `${tension}#11`;
  if (has('m13')) alterations += `${tension}b13`;
  if (has('m6')) alterations += 'b6';

  const body = seventh
    ? `${base}${sus}${alterations}${adds.join('')}${omits}`
    : `${base}${sus}${adds.join('')}${alterations}${omits}`;
  // A suffix that starts with an accidental would be read as part of the root (Cb5 is C flat).
  return /^[b#]/.test(body) ? `(${body})` : body;
}

function customType(intervals: string[]): ChordType {
  const symbol = symbolForIntervals(intervals);
  const has = (name: string) => intervals.includes(name);
  const hasSeventh = has('m7') || has('M7') || has('d7');
  const alteredTension = ['m9', 'A9', 'A11', 'm13'].some(has) || ((has('d5') || has('A5')) && has('m7') && has('M3'));
  const tension = ['M9', 'P11', 'M13'].some(has);
  const category: ChordCategory = hasSeventh
    ? alteredTension ? 'altered' : tension ? 'extended' : 'seventh'
    : has('M6') ? 'sixth' : intervals.length > 3 ? 'added' : 'triad';
  const id = symbol.replace(/#/g, 'sharp').replace(/[^A-Za-z0-9]/g, '').toLowerCase() || 'custom';
  return buildType(id, symbol, symbol === '' ? 'major' : `${symbol} chord`, intervals, [], category, 4, '', true);
}

function typeForIntervals(intervals: string[]): ChordType {
  return TYPES_BY_INTERVALS.get(intervalKey(intervals)) ?? customType(intervals);
}

function makeChord(root: Note, type: ChordType, bass: Note | null): Chord {
  const notes = type.intervals.map((i) => transpose(root.pcName, i));
  const chromas = notes.map((n) => note(n).chroma);
  let bassName: string | null = null;
  let inversion: number | null = 0;
  if (bass && bass.chroma !== root.chroma) {
    const index = chromas.indexOf(bass.chroma);
    inversion = index >= 0 ? index : null;
    bassName = bass.pcName;
  }
  return {
    symbol: `${root.pcName}${type.symbol}${bassName ? `/${bassName}` : ''}`,
    root: root.pcName,
    type,
    bass: bassName,
    notes,
    inversion,
  };
}

const ROOT_RE = /^([A-H])((?:#|b|♯|♭|𝄪|𝄫){0,2})/u;
// Tab sites often write the bass in lower case (D/f#, G/b); after a slash that is unambiguous.
const BASS_RE = /\/\s*([A-Ha-h](?:#|b|♯|♭|𝄪|𝄫){0,2})\s*$/u;

/** Options for `parseChord`. */
export interface ParseChordOptions {
  /** Read roots the German way: `H` is B natural and a bare `B` is B flat (`Hm`, `B7`). */
  german?: boolean;
}

function readRoot(text: string, german: boolean): Note | null {
  if (text[0] === 'H') return german ? parseNote(`B${text.slice(1)}`) : null;
  if (german && text === 'B') return parseNote('Bb');
  return parseNote(text);
}

/**
 * Parse a chord symbol as written on real charts: `F#m7b5/A`, `Bbmaj7`, `C-7`, `Gsus`, `A7(#9)`,
 * `Dadd9/F#`, `C△9`, `Bø7`, `E°7`, `G+`. Returns null for `N.C.` and for text that is not a chord.
 *
 * An accidental straight after the root letter belongs to the root: `Cb5` is a C flat power
 * chord. Write `C(b5)` for the altered triad.
 */
export function parseChord(symbol: string, opts: ParseChordOptions = {}): Chord | null {
  if (typeof symbol !== 'string') return null;
  // Degree-sign lookalikes first (NFKC would turn a superscript zero into a digit), then fold
  // superscripts and full-width forms into plain characters: C⁷ -> C7, Cᵐᵃʲ⁷ -> Cmaj7.
  const text = symbol.trim().replace(/[º˚⁰ᵒ]/g, '°').normalize('NFKC');
  if (!text || isNoChord(text)) return null;
  const rootMatch = ROOT_RE.exec(text);
  if (!rootMatch) return null;
  const root = readRoot(rootMatch[0], !!opts.german);
  if (!root) return null;
  let suffix = text.slice(rootMatch[0].length);
  let bass: Note | null = null;
  const slash = BASS_RE.exec(suffix);
  if (slash) {
    bass = readRoot(slash[1][0].toUpperCase() + slash[1].slice(1), !!opts.german);
    if (!bass) return null;
    suffix = suffix.slice(0, slash.index);
  }
  if (/\/\s*$/.test(suffix)) return null;
  const intervals = parseSuffix(suffix);
  if (!intervals) return null;
  return makeChord(root, typeForIntervals(intervals), bass);
}

/** Parse a chord symbol, throwing a RangeError when it is not a chord. */
export function chord(symbol: string | Chord): Chord {
  if (typeof symbol !== 'string') return symbol;
  const parsed = parseChord(symbol);
  if (!parsed) throw new RangeError(`Not a chord symbol: "${symbol}"`);
  return parsed;
}

/** True when the text parses as a chord symbol. */
export function isChord(symbol: string): boolean {
  return parseChord(symbol) !== null;
}

/** Canonical ASCII spelling of a chord symbol (`C-7` -> `Cm7`, `n.c.` -> `N.C.`); null when unreadable. */
export function normalizeChordSymbol(symbol: string): string | null {
  if (isNoChord(symbol)) return NO_CHORD;
  return parseChord(symbol)?.symbol ?? null;
}

/** Look a chord type up by id, canonical suffix or any alias (`maj7`, `M7`, `Δ`, `7sharp9`, `7#9`). */
export function getChordType(query: string | ChordType): ChordType | null {
  if (typeof query !== 'string') return query;
  const byId = TYPES_BY_ID.get(query);
  if (byId) return byId;
  const intervals = parseSuffix(query);
  if (!intervals) return null;
  return TYPES_BY_INTERVALS.get(intervalKey(intervals)) ?? null;
}

/** Build a chord from a root and a type (id, suffix or alias), with an optional bass note. */
export function buildChord(root: string, type: string | ChordType = 'major', bass?: string | null): Chord {
  const resolved = typeof type === 'string' ? getChordType(type) ?? chord(`C${type}`).type : type;
  return makeChord(note(root), resolved, bass ? note(bass) : null);
}

/**
 * Route-safe id for a chord: `F#m7b5` -> `f-sharp-m7b5`, `Bbmaj7` -> `bb-maj7`, `C` -> `c-major`.
 * The slash bass is not part of the id.
 */
export function chordSlug(input: string | Chord): string {
  const c = chord(input);
  return `${noteSlug(c.root)}-${c.type.id}`;
}

/** Inverse of `chordSlug` for catalog chord types; null when the slug names no chord. */
export function chordFromSlug(slug: string): Chord | null {
  const m = /^([a-g](?:-sharp|-flat|b)*)-([a-z0-9]+)$/.exec(slug.trim().toLowerCase());
  if (!m) return null;
  const root = noteFromSlug(m[1]);
  const type = TYPES_BY_ID.get(m[2]);
  return root && type ? makeChord(note(root), type, null) : null;
}

/** Filter for `filterChordTypes`. */
export interface ChordTypeFilter {
  category?: ChordCategory | ChordCategory[];
  quality?: ChordQuality | ChordQuality[];
  /** Exact tier, or use `maxTier`. */
  tier?: number;
  maxTier?: number;
  /** Number of distinct chord tones. */
  size?: number;
}

function matches<T>(want: T | T[] | undefined, value: T): boolean {
  if (want === undefined) return true;
  return Array.isArray(want) ? want.includes(value) : want === value;
}

/** Catalog types matching every given criterion. */
export function filterChordTypes(filter: ChordTypeFilter = {}): ChordType[] {
  return CHORD_TYPES.filter(
    (t) =>
      matches(filter.category, t.category) &&
      matches(filter.quality, t.quality) &&
      (filter.tier === undefined || t.tier === filter.tier) &&
      (filter.maxTier === undefined || t.tier <= filter.maxTier) &&
      (filter.size === undefined || t.intervals.length === filter.size),
  );
}

/** Free-text search over ids, symbols, names and aliases; best matches first. */
export function searchChordTypes(query: string): ChordType[] {
  const q = query.trim();
  if (!q) return [...CHORD_TYPES];
  const lower = q.toLowerCase();
  const scored: Array<{ type: ChordType; score: number }> = [];
  for (const type of CHORD_TYPES) {
    let score = 0;
    if (type.symbol === q || type.id === lower) score = 100;
    else if (type.aliases.includes(q)) score = 90;
    else if (type.name.toLowerCase() === lower) score = 85;
    else if (type.name.toLowerCase().startsWith(lower)) score = 60;
    else if (type.name.toLowerCase().includes(lower)) score = 40;
    else if (type.symbol.toLowerCase().includes(lower) || type.aliases.some((a) => a.toLowerCase().includes(lower))) score = 20;
    if (score > 0) scored.push({ type, score });
  }
  return scored.sort((a, b) => b.score - a.score).map((s) => s.type);
}

// ── Formatting ─────────────────────────────────────────────────────────────────────────────

/** Options for `formatChord`. */
export interface FormatChordOptions extends FormatNoteOptions {
  /** Use the jazz glyphs △ ø ° + instead of maj, m7b5, dim, aug. */
  jazz?: boolean;
}

function jazzSuffix(type: ChordType): string {
  const s = type.symbol;
  if (s === 'm7b5') return 'ø7';
  if (s === 'm9b5') return 'ø9';
  if (s.startsWith('dimMaj')) return `°△${s.slice(6)}`;
  if (s.startsWith('dim')) return `°${s.slice(3)}`;
  if (s === 'aug') return '+';
  if (s.startsWith('mMaj')) return `m△${s.slice(4)}`;
  if (s.startsWith('maj')) return `△${s.slice(3)}`;
  return s;
}

/**
 * Display text for a chord: `formatChord('Bbm7b5/Ab')` -> `B♭m7♭5/A♭`. Follows the naming
 * system (German `H7`, solfège `Sol7`) and can use jazz glyphs (`C△7`, `Bø7`).
 */
export function formatChord(input: string | Chord, opts: FormatChordOptions = {}): string {
  if (typeof input === 'string' && isNoChord(input)) return NO_CHORD;
  const c = chord(input);
  const noteOpts: FormatNoteOptions = { ...opts, natural: false, octave: false };
  let suffix = opts.jazz ? jazzSuffix(c.type) : c.type.symbol;
  if (!opts.ascii) {
    suffix = suffix.replace(/#/g, formatAccidental(1, noteOpts)).replace(/b/g, formatAccidental(-1, noteOpts));
  }
  const bass = c.bass ? `/${formatNote(c.bass, noteOpts)}` : '';
  return `${formatNote(c.root, noteOpts)}${suffix}${bass}`;
}

// ── Chord tones ────────────────────────────────────────────────────────────────────────────

/** Spelled notes of a chord from the root upwards; `withBass` puts a slash bass first. */
export function chordNotes(input: string | Chord, opts: { withBass?: boolean } = {}): string[] {
  const c = chord(input);
  if (!opts.withBass || !c.bass) return [...c.notes];
  const bassChroma = note(c.bass).chroma;
  return [c.bass, ...c.notes.filter((n) => note(n).chroma !== bassChroma)];
}

/** Distinct pitch classes of a chord (bass included), in chord-tone order. */
export function chordPcs(input: string | Chord): number[] {
  const c = chord(input);
  return [...new Set(chordNotes(c, { withBass: true }).map((n) => note(n).chroma))];
}

/**
 * Close-position MIDI notes for a chord with the root in `octave` (default 3, so C3 = 48; the
 * octave is that of the spelled root, so Cb3 = 47).
 * A slash bass is placed just below the root. This is a reference voicing for playback and ear
 * training; playable guitar shapes come from `core/guitar`.
 */
export function chordMidi(input: string | Chord, opts: { octave?: number } = {}): number[] {
  const c = chord(input);
  const rootMidi = note(`${c.root}${opts.octave ?? 3}`).midi!;
  const tones = c.type.semitones.map((s) => rootMidi + s);
  if (!c.bass) return tones;
  let bassMidi = rootMidi - 12 + ((note(c.bass).chroma - note(c.root).chroma + 12) % 12);
  if (bassMidi >= rootMidi) bassMidi -= 12;
  return [bassMidi, ...tones.filter((m) => (m - bassMidi) % 12 !== 0)];
}

const ROLE_BY_NUMBER: Record<number, ChordToneRole> = {
  1: 'root', 2: 'second', 3: 'third', 4: 'fourth', 5: 'fifth', 6: 'sixth', 7: 'seventh',
  9: 'ninth', 11: 'eleventh', 13: 'thirteenth',
};
const NATURAL_TENSIONS = ['M9', 'P11', 'M13'];

type ToneInfo = Omit<ChordTone, 'note'>;

function toneInfo(type: ChordType): ToneInfo[] {
  const { intervals, quality, id } = type;
  const has = (name: string) => intervals.includes(name);
  const hasThird = has('M3') || has('m3');
  const hasSeventh = has('m7') || has('M7') || has('d7');
  const highestNatural = [...intervals].reverse().find((i) => NATURAL_TENSIONS.includes(i));
  const small = intervals.length <= 3;

  return intervals.map((name, index) => {
    const ivl = interval(name);
    const role = ROLE_BY_NUMBER[ivl.number] ?? 'thirteenth';
    const isTension = ivl.number > 7;
    const altered =
      (isTension && !NATURAL_TENSIONS.includes(name)) ||
      (role === 'fifth' && name !== 'P5' && !['diminished', 'half-diminished', 'augmented'].includes(quality)) ||
      (role === 'sixth' && name !== 'M6');
    let priority: number;
    if (role === 'root') priority = 3;
    else if (role === 'third') priority = has('P11') && name === 'M3' ? 5 : 1;
    else if (role === 'seventh') priority = 1;
    else if (role === 'sixth') priority = hasSeventh ? 2 : 1;
    else if (role === 'second' || role === 'fourth') priority = hasThird ? 2 : 1;
    else if (role === 'fifth') priority = name === 'P5' ? 5 : 2;
    else priority = altered || name === highestNatural ? 2 : 4;
    let omittable = !small && priority >= 4;
    if (role === 'fifth' && name === 'P5') omittable = hasSeventh || intervals.length >= 5;
    // "Alt" names a menu rather than a fixed chord: any of its tensions may be chosen or left out.
    if (id === '7alt' && isTension) omittable = true;
    return { interval: name, degree: type.degrees[index], role, altered, priority, omittable };
  });
}

/**
 * Every tone of a chord with its role, whether it is altered, and how important it is in a
 * voicing. Priorities follow standard practice: third and seventh (the guide tones) first, then
 * the notes that give the chord its name, then the root, lesser tensions, and the perfect fifth last.
 */
export function chordTones(input: string | Chord): ChordTone[] {
  const c = chord(input);
  return toneInfo(c.type).map((info, index) => ({ note: c.notes[index], ...info }));
}

/** The tones a voicing may leave out, most dispensable first (usually the fifth, then lesser tensions). */
export function omittableTones(input: string | Chord): ChordTone[] {
  return chordTones(input).filter((t) => t.omittable).sort((a, b) => b.priority - a.priority);
}

/**
 * The `count` most important tones of a chord, for building a voicing on a limited number of
 * strings: `voicingTones('C13', 4)` -> E, Bb, A and the root.
 */
export function voicingTones(input: string | Chord, count: number): ChordTone[] {
  const tones = chordTones(input);
  const ranked = tones.map((tone, index) => ({ tone, index })).sort((a, b) => a.tone.priority - b.tone.priority || a.index - b.index);
  const keep = new Set(ranked.slice(0, Math.max(1, count)).map((r) => r.index));
  return tones.filter((_t, index) => keep.has(index));
}

// ── Transposition, inversions, relationships ──────────────────────────────────────────────

function tidyRoot(name: string): string {
  return Math.abs(note(name).alt) >= 2 ? simplifyNote(name) : name;
}

function rebuild(c: Chord, root: string, bass: string | null): Chord {
  return makeChord(note(root), c.type, bass ? note(bass) : null);
}

/** Transpose a chord symbol by an interval, keeping correct spelling (`Am7/G` + `M2` -> `Bm7/A`). */
export function transposeChord(input: string | Chord, intervalName: string): string {
  const c = chord(input);
  const root = tidyRoot(transpose(c.root, intervalName));
  const bass = c.bass ? tidyRoot(transpose(c.bass, intervalName)) : null;
  return rebuild(c, root, bass).symbol;
}

/**
 * A bass note spelled the way the chord spells it when it is a chord tone (C/E, never C/Fb).
 * One exception: when the caller named that pitch with a plain letter and the chord would call it
 * B#, E#, Cb or Fb, the plain letter stays (E+/C rather than E+/B#), which is how charts write it.
 */
function bassNameFor(root: Note, type: ChordType, bassPc: number, given?: string): string {
  const tones = type.intervals.map((i) => transpose(root.pcName, i));
  const tone = tones.find((t) => note(t).chroma === bassPc);
  if (tone) {
    const t = note(tone);
    if (Math.abs(t.alt) >= 2) return simplifyNote(tone);
    if (t.alt !== 0 && given && note(given).alt === 0) return given;
    return tone;
  }
  return given ?? pcToNote(bassPc, root.alt < 0 ? 'flats' : root.alt > 0 ? 'sharps' : 'auto');
}

/**
 * Transpose a chord symbol by semitones. The new root takes the spelling that gives the chord
 * the fewest accidentals (C#m rather than Dbm) unless `prefer` forces sharps or flats.
 */
export function transposeChordBySemitones(input: string | Chord, semis: number, prefer: AccidentalPreference = 'auto'): string {
  const c = chord(input);
  const shift = Math.round(semis);
  const move = (name: string) => (((note(name).chroma + shift) % 12) + 12) % 12;
  const root = note(bestRootName(move(c.root), c.type, prefer));
  const bass = c.bass ? note(bassNameFor(root, c.type, move(c.bass))) : null;
  return makeChord(root, c.type, bass).symbol;
}

/** The slash chord with the `n`th chord tone in the bass (`invertChord('C', 1)` -> `C/E`; 0 = root position). */
export function invertChord(input: string | Chord, n: number): string {
  const c = chord(input);
  const count = c.notes.length;
  const index = ((Math.round(n) % count) + count) % count;
  return rebuild(c, c.root, index === 0 ? null : c.notes[index]).symbol;
}

/** Root position followed by every inversion: `['Cmaj7', 'Cmaj7/E', 'Cmaj7/G', 'Cmaj7/B']`. */
export function chordInversions(input: string | Chord): string[] {
  const c = chord(input);
  return c.notes.map((_n, i) => invertChord(c, i));
}

const RELATIVE_OF_MAJOR: Record<string, string> = { major: 'minor', maj7: 'm7', maj9: 'm9', add9: 'madd9', 6: 'm7' };
const RELATIVE_OF_MINOR: Record<string, string> = { minor: 'major', m7: 'maj7', m9: 'maj9', madd9: 'add9' };
const PARALLEL_PAIRS: Array<[string, string]> = [
  ['major', 'minor'], ['maj7', 'm7'], ['6', 'm6'], ['69', 'm69'], ['maj9', 'm9'], ['add9', 'madd9'],
  ['add11', 'madd11'], ['maj13', 'm13'],
];

/**
 * The home chord of the relative key: `C` <-> `Am`, `Cmaj7` <-> `Am7`. Null for chord types that
 * are not a plain major or minor home chord.
 */
export function relativeChord(input: string | Chord): string | null {
  const c = chord(input);
  const down = RELATIVE_OF_MAJOR[c.type.id];
  if (down) return buildChord(transpose(c.root, '-m3'), down).symbol;
  const up = RELATIVE_OF_MINOR[c.type.id];
  if (up) return buildChord(transpose(c.root, 'm3'), up).symbol;
  return null;
}

/** The same-root chord of the parallel key: `C` <-> `Cm`, `Cmaj7` <-> `Cm7`, `C6` <-> `Cm6`. Null when there is no counterpart. */
export function parallelChord(input: string | Chord): string | null {
  const c = chord(input);
  for (const [major, minor] of PARALLEL_PAIRS) {
    if (c.type.id === major) return buildChord(c.root, minor).symbol;
    if (c.type.id === minor) return buildChord(c.root, major).symbol;
  }
  return null;
}

/** True for chords with a major third and a minor seventh, the ones that act as dominants. */
export function isDominant(input: string | Chord): boolean {
  return chord(input).type.quality === 'dominant';
}

/**
 * The tritone substitute of a dominant chord: the same type a tritone away, sharing its third
 * and seventh (`G7` -> `Db7`, `D9` -> `Ab9`). Null when the chord is not a dominant.
 */
export function tritoneSubstitute(input: string | Chord): string | null {
  const c = chord(input);
  if (c.type.quality !== 'dominant') return null;
  const target = transpose(c.root, 'd5');
  const n = note(target);
  // Cb7 and Fb7 are correct but nobody writes them; B7 and E7 are what a chart shows.
  const root = Math.abs(n.alt) >= 2 || target === 'Cb' || target === 'Fb' ? simplifyNote(target) : target;
  return buildChord(root, c.type).symbol;
}

/** A catalog type with some omittable tones left out, keyed by the pitch classes that remain. */
interface ReducedVoicing {
  type: ChordType;
  omitted: string[];
}

function subsetsOfSize<T>(items: T[], size: number): T[][] {
  if (size === 0) return [[]];
  if (items.length < size) return [];
  const [first, ...rest] = items;
  return [...subsetsOfSize(rest, size - 1).map((s) => [first, ...s]), ...subsetsOfSize(rest, size)];
}

/**
 * Incomplete voicings: every catalog type minus each combination of its omittable tones, unless
 * what remains is a catalog chord in its own right. Fewer omissions win, then catalog order.
 */
const REDUCED_VOICINGS = new Map<string, ReducedVoicing>();
for (let size = 1; size <= 3; size++) {
  for (const type of CHORD_TYPES) {
    if (type.id === '7alt') continue;
    const omittable = toneInfo(type).filter((t) => t.omittable);
    for (const subset of subsetsOfSize(omittable, size)) {
      const dropped = new Set(subset.map((t) => t.interval));
      const remaining = type.intervals.filter((i) => !dropped.has(i));
      if (remaining.length < 3) continue;
      const key = pcSetKey(remaining.map((i) => interval(i).semitones));
      if (!TYPES_BY_PCS.has(key) && !REDUCED_VOICINGS.has(key)) {
        REDUCED_VOICINGS.set(key, { type, omitted: subset.map((t) => t.degree) });
      }
    }
  }
}

// ── Identification ─────────────────────────────────────────────────────────────────────────

/** One candidate name for a set of notes. */
export interface ChordMatch {
  symbol: string;
  chord: Chord;
  /** Higher is more likely. Comparable only within one result list. */
  score: number;
  /**
   * `exact`: every note is a chord tone and none is missing. `partial`: tones a voicing may drop
   * (see `omitted`) are absent. `slash`: the lowest note is a non-chord bass under a complete chord.
   */
  kind: 'exact' | 'partial' | 'slash';
  /** Degrees of the chord that the notes leave out (`['5']`, `['5', '9']`); empty unless `partial`. */
  omitted: string[];
}

/** Options for `identifyChords`. */
export interface IdentifyOptions {
  /** Accidental preference for roots when the input is MIDI numbers. */
  prefer?: AccidentalPreference;
  /**
   * Names a pitch class when the input is MIDI numbers, overriding `prefer`. Pass
   * `(pc) => spellInKey(pc, key)` to get roots spelled for the song's key.
   */
  spell?: (pc: number) => string;
  /** Maximum number of candidates (default 8). */
  limit?: number;
  /** Also consider incomplete voicings that drop the fifth or a lesser tension (default true). */
  allowPartial?: boolean;
}

function accidentalCount(names: string[]): number {
  return names.reduce((sum, n) => sum + Math.abs(note(n).alt), 0);
}

/** Root spelling that gives the chord the fewest accidentals (C#m rather than Dbm, Db rather than C#). */
function bestRootName(pc: number, type: ChordType, prefer: AccidentalPreference = 'auto'): string {
  const sharp = pcToNote(pc, 'sharps');
  const flat = pcToNote(pc, 'flats');
  if (sharp === flat) return sharp;
  if (prefer === 'sharps') return sharp;
  if (prefer === 'flats') return flat;
  const cost = (root: string) => accidentalCount(type.intervals.map((i) => transpose(root, i)));
  const diff = cost(sharp) - cost(flat);
  if (diff !== 0) return diff < 0 ? sharp : flat;
  return pcToNote(pc, 'auto');
}

/**
 * Name the chord formed by a set of notes. Accepts note names (`['E', 'G', 'C']`, the first is
 * the bass unless every note carries an octave) or MIDI numbers (the lowest is the bass).
 * Returns ranked candidates, including inversions (`C/E`), slash chords and voicings that drop
 * the fifth or a lesser tension. An empty list means nothing in the catalog fits.
 */
export function identifyChords(input: Array<string | number>, opts: IdentifyOptions = {}): ChordMatch[] {
  const items: Array<{ chroma: number; midi: number | null; name: string | null }> = [];
  for (const item of input) {
    if (typeof item === 'number') {
      if (!Number.isFinite(item)) continue;
      const midi = Math.round(item);
      items.push({ chroma: ((midi % 12) + 12) % 12, midi, name: null });
    } else {
      // Unreadable names are skipped rather than thrown: this runs on live, messy input.
      const n = parseNote(item);
      if (n) items.push({ chroma: n.chroma, midi: n.midi, name: n.pcName });
    }
  }
  if (items.length < 2) return [];
  const allPitched = items.every((it) => it.midi !== null);
  const bassItem = allPitched ? items.reduce((low, it) => (it.midi! < low.midi! ? it : low)) : items[0];
  const pcs = [...new Set(items.map((it) => it.chroma))];
  if (pcs.length < 2) return [];
  const givenName = new Map<number, string>();
  for (const it of items) {
    if (givenName.has(it.chroma)) continue;
    const name = it.name ?? (opts.spell ? parseNote(opts.spell(it.chroma))?.pcName : undefined);
    if (name && note(name).chroma === it.chroma) givenName.set(it.chroma, name);
  }

  const out = new Map<string, ChordMatch>();
  const add = (rootPc: number, type: ChordType, kind: ChordMatch['kind'], omitted: string[], penalty = 0) => {
    const rootName = givenName.get(rootPc) ?? bestRootName(rootPc, type, opts.prefer);
    const root = note(rootName);
    const toneIndex = type.semitones.findIndex((semi) => (((rootPc + semi) % 12) + 12) % 12 === bassItem.chroma);
    const bassName = bassNameFor(root, type, bassItem.chroma, givenName.get(bassItem.chroma));
    const candidate = makeChord(root, type, note(bassName));
    const rootInBass = bassItem.chroma === rootPc;
    let score = (kind === 'exact' ? 100 : kind === 'slash' ? 62 : 64 - 4 * omitted.length) - penalty;
    // Root position is the default reading, but not at any price: an everyday chord in inversion
    // (Cmaj7/E) beats a rare chord in root position (Em(b6)) when the rare one is two tiers harder.
    if (rootInBass) score += 20;
    score -= type.tier * 12 + Math.max(0, type.intervals.length - 3);
    if (!rootInBass && toneIndex > 0) {
      // Higher inversions are rarer, and a tension in the bass (Cadd9/D) is an unlikely reading.
      score -= toneIndex;
      if (type.semitones[toneIndex] > 12) score -= 27;
    }
    score -= CHORD_TYPES.indexOf(type) * 0.001;
    const existing = out.get(candidate.symbol);
    if (!existing || existing.score < score) out.set(candidate.symbol, { symbol: candidate.symbol, chord: candidate, score, kind, omitted });
  };
  const consider = (rootPc: number, tonePcs: number[], kind: ChordMatch['kind']) => {
    const key = pcSetKey(tonePcs.map((pc) => pc - rootPc));
    const type = TYPES_BY_PCS.get(key);
    if (type) {
      add(rootPc, type, kind, []);
    } else if (kind === 'exact' && opts.allowPartial !== false) {
      const reduced = REDUCED_VOICINGS.get(key);
      if (reduced) add(rootPc, reduced.type, 'partial', reduced.omitted);
    }
  };

  for (const rootPc of pcs) consider(rootPc, pcs, 'exact');
  if (pcs.length >= 4) {
    const upper = pcs.filter((pc) => pc !== bassItem.chroma);
    for (const rootPc of upper) consider(rootPc, upper, 'slash');
  }
  if (pcs.length === 2 && out.size === 0 && opts.allowPartial !== false) {
    // A bare third implies a triad without its fifth, the way a two-note guitar double stop does;
    // a sixth is the same triad with its third in the bass. Other dyads name no chord.
    const other = pcs.find((pc) => pc !== bassItem.chroma)!;
    const size = (other - bassItem.chroma + 12) % 12;
    const major = TYPES_BY_ID.get('major')!;
    const minor = TYPES_BY_ID.get('minor')!;
    if (size === 4) add(bassItem.chroma, major, 'partial', ['5'], 20);
    else if (size === 3) add(bassItem.chroma, minor, 'partial', ['5'], 20);
    else if (size === 8) add(other, major, 'partial', ['5'], 20);
    else if (size === 9) add(other, minor, 'partial', ['5'], 20);
  }
  return [...out.values()].sort((a, b) => b.score - a.score).slice(0, opts.limit ?? 8);
}

/** The single most likely chord symbol for a set of notes, or null when nothing fits. */
export function identifyChord(input: Array<string | number>, opts: IdentifyOptions = {}): string | null {
  return identifyChords(input, opts)[0]?.symbol ?? null;
}

/**
 * The chord type whose tones sit at the given semitone offsets above a root, or a generated one
 * when the catalog has none. Used to name the chords found by stacking thirds in unusual scales.
 */
export function chordTypeFromSemitones(semis: number[]): ChordType {
  const set = new Set(semis.map((s) => ((s % 12) + 12) % 12));
  set.add(0);
  const found = TYPES_BY_PCS.get(pcSetKey(set));
  if (found) return found;
  const has = (n: number) => set.has(n);
  const third = has(4) ? 'M3' : has(3) ? 'm3' : null;
  const list = ['P1'];
  if (third) list.push(third);
  if (has(3) && third === 'M3') list.push('A9');
  // A diminished seventh needs its diminished fifth: with a perfect fifth too, the "bb7" is a sixth.
  const seventh = has(10) ? 'm7' : has(11) ? 'M7' : has(9) && third === 'm3' && has(6) && !has(7) ? 'd7' : null;
  if (seventh) list.push(seventh);
  if (has(7)) list.push('P5');
  if (has(6)) list.push(has(7) ? 'A11' : 'd5');
  if (has(8)) list.push(has(7) || has(6) ? (seventh ? 'm13' : 'm6') : 'A5');
  if (has(9) && seventh !== 'd7') list.push(seventh ? 'M13' : 'M6');
  if (has(2)) list.push(third ? 'M9' : 'M2');
  if (has(5)) list.push(third ? (seventh ? 'P11' : 'P4') : 'P4');
  if (has(1)) list.push('m9');
  return typeForIntervals(sortIntervals(list));
}

/**
 * The chord type with exactly these intervals above its root (`['P1','m3','d5']` -> dim). Falls
 * back to the sound (semitones) when the spelling is one no chord symbol uses, such as the
 * diminished third that stacked thirds produce in the double harmonic scale.
 */
export function chordTypeFromIntervals(intervals: string[]): ChordType {
  const sorted = sortIntervals(['P1', ...intervals]);
  const exact = TYPES_BY_INTERVALS.get(intervalKey(sorted));
  if (exact) return exact;
  return chordTypeFromSemitones(sorted.map((i) => interval(i).semitones));
}

/** Give a chord's notes octaves, ascending from the root in `octave`: `['C3','E3','G3','Bb3','D4']`. */
export function chordNotesFrom(input: string | Chord, octave = 3): string[] {
  const c = chord(input);
  const rootMidi = note(`${c.root}${octave}`).midi!;
  return c.notes.map((n, i) => withOctaveFor(n, rootMidi + c.type.semitones[i]));
}
