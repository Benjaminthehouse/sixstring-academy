/**
 * Chords: the type catalog, a parser for real-world chord symbols, canonical formatting, spelled
 * chord tones and their roles, identification from notes, inversions and relationships.
 *
 * The parser is structural, not a lookup table: it reads a symbol the way a musician does
 * (quality, highest extension, alterations, added and omitted notes, slash bass) and produces an
 * interval set. That set is then matched against the catalog; a set the catalog does not hold
 * still yields a usable chord with a generated canonical symbol (`custom: true`).
 */
import { RAW_CHORD_TYPES, type ChordCategory } from './chord-catalog';
import { degreeToInterval, interval, intervalToDegree, transpose } from './interval';
import {
  formatAccidental, formatNote, note, noteFromSlug, noteSlug, parseNote, pcToNote, simplifyNote, withOctaveFor,
  type AccidentalPreference, type FormatNoteOptions, type Note,
} from './note';

/** Broad family of a chord type; see `chord-catalog.ts`. */
export type { ChordCategory } from './chord-catalog';

/** The harmonic character of a chord type, derived from its intervals. */
export type ChordQuality =
  | 'major' | 'minor' | 'dominant' | 'diminished' | 'half-diminished' | 'augmented' | 'suspended' | 'power';

/** A kind of chord, independent of its root. */
export interface ChordType {
  /** Stable, route-safe id: `major`, `m7b5`, `7sharp9`, `69`. */
  id: string;
  /** Canonical suffix written after the root: `''`, `m`, `maj7`, `7#9`, `6/9`. */
  symbol: string;
  /** English name: `minor seventh`. */
  name: string;
  /** Other suffixes found on charts: `M7`, `Δ`, `-7`, `ø`, `°7`, `+` … */
  aliases: string[];
  /** Intervals above the root, ascending: `['P1','M3','P5','m7']`. */
  intervals: string[];
  /** The same as degree labels: `['1','3','5','b7']`. */
  degrees: string[];
  /** Semitones above the root, ascending (tensions stay above the octave: a ninth is 14). */
  semitones: number[];
  category: ChordCategory;
  quality: ChordQuality;
  /** Short description of the sound and its use. Empty for generated types. */
  description: string;
  /** 1 beginner … 4 expert. */
  tier: 1 | 2 | 3 | 4;
  /** True for a type generated by the parser because the catalog does not hold it. */
  custom: boolean;
}

/** A chord: a root, a type and an optional slash bass. */
export interface Chord {
  /** Canonical ASCII symbol: `F#m7b5/A`. */
  symbol: string;
  root: string;
  type: ChordType;
  /** Slash bass note, or null when the root is in the bass. */
  bass: string | null;
  /** Spelled chord tones from the root upwards, without octaves. The bass is not added. */
  notes: string[];
  /** 0 = root position, 1 = first inversion …; null when the bass is not a chord tone. */
  inversion: number | null;
}

/** The job a note does inside a chord. */
export type ChordToneRole =
  | 'root' | 'second' | 'third' | 'fourth' | 'fifth' | 'sixth' | 'seventh' | 'ninth' | 'eleventh' | 'thirteenth';

/** One tone of a chord with its role and how dispensable it is in a voicing. */
export interface ChordTone {
  note: string;
  interval: string;
  degree: string;
  role: ChordToneRole;
  /** True for a raised or lowered fifth, ninth, eleventh or thirteenth that is not part of the basic quality. */
  altered: boolean;
  /** Voicing importance, 1 = keep first (guide tones) … 5 = drop first (perfect fifth). */
  priority: number;
  /** True when a voicing may leave this tone out without changing what the chord is. */
  omittable: boolean;
}

// ── Catalog ────────────────────────────────────────────────────────────────────────────────

function sortIntervals(list: Iterable<string>): string[] {
  return [...new Set(list)].sort((a, b) => interval(a).semitones - interval(b).semitones || interval(a).steps - interval(b).steps);
}

function intervalKey(list: string[]): string {
  return list.join(' ');
}

function qualityOf(intervals: string[]): ChordQuality {
  const has = (name: string) => intervals.includes(name);
  if (has('M3')) {
    if (has('m7')) return 'dominant';
    return has('A5') ? 'augmented' : 'major';
  }
  if (has('m3')) {
    if (has('d5')) return has('m7') ? 'half-diminished' : 'diminished';
    return 'minor';
  }
  return intervals.length === 2 && has('P5') ? 'power' : 'suspended';
}

function buildType(
  id: string, symbol: string, name: string, intervals: string[], aliases: string[],
  category: ChordCategory, tier: 1 | 2 | 3 | 4, description: string, custom: boolean,
): ChordType {
  return {
    id, symbol, name, aliases, intervals,
    degrees: intervals.map(intervalToDegree),
    semitones: intervals.map((i) => interval(i).semitones),
    category,
    quality: qualityOf(intervals),
    description, tier, custom,
  };
}

/** Every chord type in the catalog, grouped by category in teaching order. */
export const CHORD_TYPES: readonly ChordType[] = RAW_CHORD_TYPES.map((raw) =>
  buildType(
    raw.id, raw.symbol, raw.name, sortIntervals(raw.formula.split(/\s+/).map(degreeToInterval)),
    raw.aliases, raw.category, raw.tier, raw.description, false,
  ),
);

const TYPES_BY_ID = new Map(CHORD_TYPES.map((t) => [t.id, t]));
const TYPES_BY_INTERVALS = new Map(CHORD_TYPES.map((t) => [intervalKey(t.intervals), t]));

function pcSetKey(semis: Iterable<number>): string {
  return [...new Set([...semis].map((s) => ((s % 12) + 12) % 12))].sort((a, b) => a - b).join(',');
}

/** First catalog type for each pitch-class set (catalog order decides between add11 and add4). */
const TYPES_BY_PCS = new Map<string, ChordType>();
for (const t of CHORD_TYPES) {
  const key = pcSetKey(t.semitones);
  if (!TYPES_BY_PCS.has(key)) TYPES_BY_PCS.set(key, t);
}
