#!/usr/bin/env node
/**
 * Regenerates the icon data used by <Icon> from the installed lucide-react package.
 *
 *   node src/ui/icon/generate.mjs
 *
 * Reads   bundled-names.txt        the icons that ship in the main bundle (one lucide name per line)
 * Writes  bundled.generated.ts     drawing data for those names (plus their lucide aliases)
 *         all.generated.ts         drawing data for every lucide icon (as JSON text), loaded lazily for other names
 *
 * Why data instead of importing the components: a name -> component lookup needs lucide's whole
 * barrel module, and the bundler then keeps all ~2000 icons (1 MB) in whichever chunk touches it.
 * Plain data keeps the critical path small and leaves other files free to import single icons from
 * lucide-react with normal tree-shaking. icons.test.tsx checks this data against lucide's own output.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('lucide-react/package.json'));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const esmDir = path.join(pkgDir, 'dist', 'esm');
const barrel = fs.readFileSync(path.join(esmDir, 'lucide-react.mjs'), 'utf8');

/** Every `export { default as A, default as B } from './icons/file.mjs'` line of the barrel. */
const files = new Map();
for (const m of barrel.matchAll(/export\s*\{([^}]+)\}\s*from\s*'\.\/icons\/([^']+)\.mjs'/g)) {
  const names = [...m[1].matchAll(/default as (\w+)/g)].map((x) => x[1]);
  if (names.length) files.set(m[2], names);
}

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
function cleanNode(node) {
  return node.map(([tag, attrs, children]) => {
    const out = {};
    for (const [k, v] of Object.entries(attrs)) if (k !== 'key') out[camel(k)] = String(v);
    if (children && children.length) throw new Error(`nested icon node in <${tag}>: extend the renderer first`);
    return [tag, out];
  });
}

const icons = {}; // canonical name -> node
const aliases = {}; // other name -> canonical name
for (const [file, names] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
  const mod = await import(pathToFileURL(path.join(esmDir, 'icons', `${file}.mjs`)).href);
  if (!mod.__iconData) continue; // an alias file that only re-exports another icon
  const canonical = mod.default.displayName;
  if (!canonical || !names.includes(canonical)) throw new Error(`cannot find the canonical name of ${file}`);
  icons[canonical] = cleanNode(mod.__iconData.node);
  const set = new Set(names);
  for (const name of names) {
    if (name === canonical) continue;
    // Skip the FooIcon / LucideFoo spellings of names that are exported anyway.
    if (name.endsWith('Icon') && set.has(name.slice(0, -4))) continue;
    if (name.startsWith('Lucide') && set.has(name.slice(6))) continue;
    aliases[name] = canonical;
  }
}

const wanted = [...new Set(fs.readFileSync(path.join(here, 'bundled-names.txt'), 'utf8').split(/\s+/).filter(Boolean))].sort();
const unknown = wanted.filter((n) => !icons[n] && !aliases[n]);
if (unknown.length) {
  console.error(`Not lucide icon names: ${unknown.join(', ')}`);
  process.exit(1);
}

// Bundle each wanted icon once, under its canonical name and every alias, so old and new names both resolve.
const canonicalWanted = [...new Set(wanted.map((n) => aliases[n] ?? n))].sort();
const aliasesOf = (canonical) => Object.keys(aliases).filter((a) => aliases[a] === canonical).sort();
const lines = [
  `// Generated by src/ui/icon/generate.mjs from lucide-react ${version}. Do not edit by hand:`,
  '// add names to bundled-names.txt and run the script again.',
  "import type { IconNode } from './types';",
  '',
  ...canonicalWanted.map((name, i) => `const n${i}: IconNode = ${JSON.stringify(icons[name])};`),
  '',
  '/** Drawing data for the icons that ship in the main bundle, by lucide name (aliases included). */',
  'export const BUNDLED_ICONS: Record<string, IconNode> = {',
  ...canonicalWanted.flatMap((name, i) => [name, ...aliasesOf(name)].map((key) => `  ${key}: n${i},`)),
  '};',
  '',
];
fs.writeFileSync(path.join(here, 'bundled.generated.ts'), lines.join('\n'));
// The complete set ships as JSON text inside a module: one string literal costs the type checker
// nothing (a 450 kB JSON import adds a second to every tsc run) and JSON.parse is the fastest way in.
const allJson = JSON.stringify({ version, icons, aliases });
if (/['\\\n]/.test(allJson)) throw new Error('icon data contains a quote or backslash: escape it before embedding');
fs.writeFileSync(
  path.join(here, 'all.generated.ts'),
  [
    `// Generated by src/ui/icon/generate.mjs from lucide-react ${version}. Do not edit by hand.`,
    '/** Every lucide icon as JSON text: `{ version, icons: { Name: node }, aliases: { Alias: Name } }`. Parsed on first use. */',
    `export default '${allJson}';`,
    '',
  ].join('\n'),
);
const size = (f) => `${Math.round(fs.statSync(path.join(here, f)).size / 1024)} kB`;
console.log(`lucide-react ${version}: ${Object.keys(icons).length} icons, ${Object.keys(aliases).length} aliases`);
console.log(`bundled.generated.ts  ${canonicalWanted.length} icons  ${size('bundled.generated.ts')}`);
console.log(`all.generated.ts      ${size('all.generated.ts')}`);
