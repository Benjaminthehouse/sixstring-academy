/**
 * Theory Path, unit 6: Notes on the neck. Written from the syllabus entries in
 * `src/content/plan/theory-path.json` (unit `notes-on-the-neck`), one lesson per entry, in order:
 * each lesson opens with the "on the guitar" picture, asks the planned exercises, ends with the
 * planned drills, and turns every planned fact into a review card. `notes-on-the-neck.test.ts`
 * cross-checks every fret, note and octave shape the text quotes against the guitar engine.
 *
 * A fretboard figure is at most 13 frets wide, so "string 6, frets 0 to 15" is drawn as two
 * pictures: frets 0 to 12, then frets 12 to 17. The octave-finding drill (`interval-on-neck`) picks
 * its root anywhere in its fret range; near the top of the range the usual shape runs off the
 * picture and the only octave left in view is on another string. The drill accepts any right place,
 * and its explanation says why, so the lessons also ask the shapes themselves in authored steps.
 */
