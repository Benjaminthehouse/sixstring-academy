/**
 * Theory Path, unit 8: Why a chord is major or minor. Written from the syllabus entries in
 * `src/content/plan/theory-path.json` (unit `major-and-minor-chords`), one lesson per entry, in
 * order: each lesson opens with the "on the guitar" picture, asks the planned exercises, ends with
 * the planned drills, and turns every planned fact into a review card.
 *
 * `major-and-minor-chords.test.ts` cross-checks every shape, note, third, fret count and listening
 * question against `@/core/theory` and `@/core/guitar`.
 *
 * Notes for readers of the code:
 * - `teaches` is shown as plain text on the map, so it spells chords out in words ("E minor").
 * - A chord box cannot label its dots, so the root, third and fifth are labelled on a fretboard
 *   figure of the same shape (string 1 on top), and the chord box shows the shape itself.
 * - A match-pairs side must differ from every other, so "match the five strings of open C to
 *   their notes" became three pairs (strings 5, 4, 3: C, E, G) plus a question on the repeats.
 * - Box-reading exercises accept only the shape in the box (`this-shape`): reading it is the point.
 * - Every listening question has a quiet twin (choice, true-false, fill-blanks), so the unit still
 *   teaches with Sound off; every play step falls back to placing the same chord.
 */
import type { FretDot, Lesson, Unit } from '@/lessons';

const U = 'major-and-minor-chords';

const dot = (string: number, fret: number, note: string, extra: Partial<FretDot> = {}): FretDot => ({ string, fret, note, ...extra });
/** A dot labelled with its fret number, as the six-character spelling writes it. */
const digit = (string: number, fret: number, note: string): FretDot => dot(string, fret, note, { label: String(fret) });

/** Open Em (022000), string 6 to string 1, sounding notes. */
const EM: Array<[number, number, string]> = [[6, 0, 'E2'], [5, 2, 'B2'], [4, 2, 'E3'], [3, 0, 'G3'], [2, 0, 'B3'], [1, 0, 'E4']];
/** Open C (x32010): string 6 is not played. */
const C: Array<[number, number, string]> = [[5, 3, 'C3'], [4, 2, 'E3'], [3, 0, 'G3'], [2, 1, 'C4'], [1, 0, 'E4']];

/** A shape on the fretboard with each dot labelled R, 3, b3 or 5 against `root`. */
function degreeDots(shape: Array<[number, number, string, string]>): FretDot[] {
  return shape.map(([s, f, n, d]) => dot(s, f, n, d === '1' ? { degree: d, label: 'R', role: 'root' } : { degree: d, role: d === '5' ? 'fifth' : 'third' }));
}

