import { it } from 'vitest';
import * as T from '@/core/theory';
import * as G from '@/core/guitar';
it('probe', () => {
  const log = (...a: unknown[]) => process.stdout.write(a.map((x) => JSON.stringify(x)).join(' ') + '\n');
  log(T.getScale('whole-tone')!.name, T.getScale('diminished-half-whole')!.name, T.getScale('diminished-whole-half')!.name, T.getScale('minor-blues')!.name);
  for (const c of ['C', 'D', 'G', 'A', 'Am']) log(c, G.libraryVoicings(c, { categories: ['caged', 'barre', 'open'] }).map((v) => [v.shape, v.category, v.label, v.frets.join(',')]));
  log(G.arpeggioPatterns('C').map((p) => [p.shape, p.minFret, p.maxFret, p.notes.length]));
  log(T.transposeChordBySemitones('G', 3), T.transposeChordBySemitones('D', 1), T.transposeChordBySemitones('Em', 6), T.transposeChordBySemitones('A', 1));
  log(G.identifyFretted('320003', { capo: 3 }).symbol, G.identifyFretted([3,2,0,0,0,3], { capo: 3 }).symbol);
  log(T.practicalKey('A# major')?.name, T.simplestTonic('A#', 'major'));
  log(T.diatonicChords('G').map((c) => [c.degree, c.symbol, c.type.id, c.roman]));
  log(T.keySignature(2), T.keyFromSignature(-3, 'minor').name);
  log(G.fretDistance(7), G.fretDistance(5), G.fretDistance(4), G.fretDistance(9), G.fretDistance(19), G.fretDistance(3));
  log(G.planFingering([55, 57, 59, 60, 62], { preferPosition: 1, minFret: 0, maxFret: 4 }).notes.map((n) => [n.string, n.fret, n.finger]));
  log(T.spellInKey(66, 'G major'), T.spellInKey(66, 'Gb major'), T.spellInKey(61, 'A minor'));
  log(T.chordToRoman('Bb', 'C'), T.romanToChord('#iv°', 'C'), T.romanToChord('vii°', 'A minor'), T.romanToChord('VI', 'A minor'), T.romanToChord('III', 'A minor'));
  log(T.romanToChord('vii°/V', 'C'), T.romanToChord('V/vi', 'C'), T.romanToChord('IV/IV', 'C'), T.romanToChord('V7/IV', 'C'), T.romanToChord('bII', 'C'), T.romanToChord('subV7', 'C'), T.parseRoman('V/V/V'), T.romanToChord('bVII', 'A'));
  log(T.midiToNote(61), T.midiToNote(63), T.midiToNote(66), T.midiToNote(68), T.midiToNote(70));
  log(T.parallelChord('B7'), T.parallelChord('G'));
});
